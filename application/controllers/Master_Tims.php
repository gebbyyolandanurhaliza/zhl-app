  function save_customer_transport()
  {
    $data = $this->input->post(null, true);

    $createdby = strtoupper($this->session->userdata('userid_1'));
    $createddate = date('Y-m-d H:i:s');

    $check = $this->input->post('is_supplier');

    if ($check == 'on') {
      $is_supplier = '1';
    } else {
      $is_supplier = '0';
    }

    $data = [
      'customer_id'      => $this->input->post('customer_id', true),
      'customer_name'    => $this->input->post('customer_name', true),
      'customer_code'    => $this->input->post('customer_code', true),
      'curency_code'     => $this->input->post('curency_code', true),
      'address'          => $this->input->post('address', true),
      'country'          => $this->input->post('country', true),
      'contact_name'     => $this->input->post('contact_name', true),
      'fax'              => $this->input->post('fax', true),
      'email'            => $this->input->post('email', true),
      'phone'            => $this->input->post('phone', true),
      'term_payment_due' => $this->input->post('term_payment_due', true),
      'balance_due_date' => $this->input->post('balance_due_date', true),
      'account'          => $this->input->post('account', true),
      'payment_method'   => $this->input->post('payment_method', true),
      'createby'         => $createdby,
      'createddate'      => $createddate,
      'is_supplier'      => $is_supplier,
    ];

    $id = $this->input->post('customer_code', true);

    $exists_in_mst_table = $this->m_tims->cek_mst_table($id);

    if ($exists_in_mst_table) {
      $this->session->set_flashdata('message', pesan('Customer Code already exists', pesan_error()));
    } else {
      $this->m_tims->save_customer_transport($data);
      $this->session->set_flashdata('message', pesan('Save Customer Transport Success', pesan_sukses()));
    }
    redirect(site_url("Master_Tims/add_customer_transport"));
  }

