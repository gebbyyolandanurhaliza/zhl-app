      'term_payment_due'         => $this->input->post('term_payment_due', true),
      'balance_due_date'         => $this->input->post('balance_due_date', true),
      'account'                  => $this->input->post('account', true),
      'payment_method'           => $this->input->post('payment_method', true),
      'updatedby'                 => $updatedby,
      'updateddate'               => $updateddate
    ];

    $new_customer_code = $this->input->post('customer_code', true);
    $old_customer_code = $this->m_tims->get_customer_code_by_id($id);

    if ($new_customer_code != $old_customer_code) {
      $exists_in_mst_table = $this->m_tims->cek_mst_table($new_customer_code);

      if ($exists_in_mst_table) {
        $this->session->set_flashdata('message', pesan('Customer Code already exists', pesan_error()));
        redirect(site_url("Master_Tims/Edit_customer_transport?customer_id=$id"));
      }
    }

    $this->m_tims->update_customer_transport($data, $id);

    $this->session->set_flashdata('message', pesan('Update Record Success', pesan_sukses()));
    redirect(site_url("Master_Tims/Edit_customer_transport?customer_id=$id"));
  }

