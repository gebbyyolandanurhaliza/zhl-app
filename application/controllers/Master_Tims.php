  public function driver_save()
  {
    $data = $this->input->post(null, true);

    $username = explode(' ', $data['driver_name']);
    $rand = rand(100, 999);

    $data['driver_loginid']   = $username[0] . $rand;
    $data['driver_loginpass'] = md5(sha1($data['driver_loginpass']));
    $data['psa_pass_exp']     = convert_tgl_db_2($data['psa_pass_exp']);
    $data['license_exp']      = convert_tgl_db_2($data['license_exp']);
    $data['created_by']       = strtoupper($this->session->userdata('userid_1'));
    $data['created_date']     = date('Y-m-d H: i: s');

    $save = $this->m_tims->save_driver($data);

    if (!$save) {
      $this->session->set_flashdata('message', pesan('Save Driver', pesan_error()));
    } else {
      $this->session->set_flashdata('message', pesan('Add Driver', pesan_sukses()));
    }
    redirect(site_url('Master_Tims/driver-add'));
  }

